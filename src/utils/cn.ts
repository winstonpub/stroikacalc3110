/* ============================================================================
 * ФАЙЛ: src/utils/cn.ts — Склейка CSS-классов оформления
 * ЗА ЧТО ОТВЕЧАЕТ: Аккуратно объединяет несколько классов Tailwind CSS в одну строку и убирает конфликтующие стили (например, когда кнопка меняет цвет в активном состоянии).
 * ОТКУДА БЕРЁТ ИНФОРМАЦИЮ: Принимает названия классов и логические условия из любых компонентов сайта.
 * КАК ИЗМЕНИТЬ: Служебная функция — редактировать её не нужно.
 * ========================================================================= */

import { clsx, type ClassValue } from "clsx";
import { twMerge } from "tailwind-merge";

/* БЛОК: Функция объединения классов (cn)
 * ЗА ЧТО ОТВЕЧАЕТ: Собирает условные классы через clsx и разрешает конфликты Tailwind через twMerge.
 * ОТКУДА БЕРЁТ ИНФОРМАЦИЮ: Из переданных аргументов inputs в атрибутах className компонентов.
 * КАК ИЗМЕНИТЬ: Не требует изменений. */
export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}
